"""Physics-informed SYNTHETIC solar data generator.

This data is NOT measured. It is produced from simple solar-geometry and
panel-physics formulas plus random noise so that the whole ML pipeline can be
demonstrated offline. Replace it with real measurements for real accuracy.
"""
import json
import numpy as np
import pandas as pd
from .config import DATA_PATH, DATA_INFO_PATH, DATA_DIR

PANEL_KW = 5.0      # assumed 5 kW rooftop system
LATITUDE = 26.0     # degrees North (northern India)


def generate_synthetic_data(days: int = 730, seed: int = 42, start: str = "2023-01-01",
                            missing_rate: float = 0.01) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    ts = pd.date_range(start, periods=days * 24, freq="h")
    n = len(ts)
    doy = ts.dayofyear.to_numpy()
    hour = ts.hour.to_numpy()

    # 1. Solar geometry -> clear-sky irradiance
    lat = np.radians(LATITUDE)
    decl = np.radians(23.45) * np.sin(2 * np.pi * (284 + doy) / 365)
    hour_angle = np.radians(15 * (hour + 0.5 - 12))
    sin_elev = np.sin(lat) * np.sin(decl) + np.cos(lat) * np.cos(decl) * np.cos(hour_angle)
    sin_elev = np.clip(sin_elev, 0, None)
    clear_sky = 1050 * sin_elev ** 1.15

    # 2. Cloud cover: persistent random process with a monsoon-like season
    season = 45 + 30 * np.sin(2 * np.pi * (doy - 120) / 365)
    cloud = np.empty(n)
    cloud[0] = season[0]
    shocks = rng.normal(0, 9, n)
    for i in range(1, n):
        cloud[i] = 0.92 * cloud[i - 1] + 0.08 * season[i] + shocks[i]
    cloud = np.clip(cloud, 0, 100)

    # 3. Irradiance reaching the panel
    irradiance = clear_sky * (1 - 0.75 * (cloud / 100) ** 2.5) * rng.normal(1, 0.04, n)
    irradiance = np.clip(irradiance, 0, 1200)

    # 4. Weather
    temp = (25 + 9 * np.sin(2 * np.pi * (doy - 100) / 365)
            + 6 * np.sin(2 * np.pi * (hour - 9) / 24) - 0.03 * cloud + rng.normal(0, 1.2, n))
    humidity = np.clip(70 - 1.2 * (temp - 25) + 0.25 * (cloud - 50) + rng.normal(0, 6, n), 10, 100)
    wind = np.clip(rng.gamma(2.0, 1.2, n) + 0.8 * sin_elev, 0, 20)

    # 5. Panel physics -> power (kW)
    cell_temp = temp + irradiance * (0.032 - 0.0012 * wind)          # panel heats up, wind cools it
    temp_eff = 1 - 0.004 * (cell_temp - 25)                           # ~0.4 %/°C power loss
    humid_eff = 1 - 0.0003 * np.clip(humidity - 60, 0, None)
    power = PANEL_KW * (irradiance / 1000) * temp_eff * 0.86 * humid_eff
    power = np.clip(power * rng.normal(1, 0.03, n), 0, None)

    df = pd.DataFrame({
        "timestamp": ts, "irradiance": irradiance.round(1), "temperature": temp.round(1),
        "humidity": humidity.round(1), "wind_speed": wind.round(1),
        "cloud_cover": cloud.round(1), "hour": hour, "power_kw": power.round(3),
    })

    # 6. Inject a few missing values so preprocessing has real work to do
    for col in ["irradiance", "temperature", "humidity", "wind_speed", "cloud_cover"]:
        df.loc[rng.random(n) < missing_rate, col] = np.nan
    df.loc[rng.random(n) < 0.002, "power_kw"] = np.nan
    return df


def save_synthetic_dataset(path=DATA_PATH, **kwargs) -> pd.DataFrame:
    df = generate_synthetic_data(**kwargs)
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    df.to_csv(path, index=False)
    info = {
        "name": "SolarPower AI synthetic dataset",
        "is_synthetic": True,
        "source": "Generated by backend/app/data_gen.py (solar geometry + panel physics + noise). Not measured data.",
        "rows": int(len(df)),
        "start": str(df["timestamp"].min()), "end": str(df["timestamp"].max()),
        "panel_capacity_kw": PANEL_KW,
        "note": "Scores on this data show the pipeline works; they do not show real-world accuracy.",
    }
    DATA_INFO_PATH.write_text(json.dumps(info, indent=2), encoding="utf-8")
    return df
